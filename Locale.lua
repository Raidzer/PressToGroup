function PTG:L(key, ...)
    local locale = self.db and self.db.locale or "auto"
    if locale == "auto" then locale = GetLocale() end
    local dictionary = strings[locale] or strings.enUS
    local stepKey
    if self.db and self.db.inputMode == "key" and (key == "ready_search" or key == "activation_4") then
        local primary, secondary, reason = self.Input.GetStepKeys()
        stepKey = primary or secondary
        if stepKey then stepKey = GetBindingText(stepKey) end
        key = key .. (reason and "_key_unavailable" or stepKey and "_key" or "_key_unbound")
    end
    local value = dictionary[key] or strings.enUS[key] or tostring(key)
    if stepKey then return string.format(value, stepKey) end
    if select("#", ...) > 0 then
        local ok, formatted = pcall(string.format, value, ...)
        if ok then return formatted end
    end
    return value
end
