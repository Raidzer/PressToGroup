function PTG:L(key, ...)
    local locale = self.db and self.db.locale or "auto"
    if locale == "auto" then locale = GetLocale() end
    local dictionary = strings[locale] or strings.enUS
    local value = dictionary[key] or strings.enUS[key] or tostring(key)
    if select("#", ...) > 0 then
        local ok, formatted = pcall(string.format, value, ...)
        if ok then return formatted end
    end
    return value
end
